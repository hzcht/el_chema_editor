package core

// T-соединение (идея 1.3, открытый вопрос О1 §4.6): конец провода может
// упираться не в пин, а в точку на уже существующем проводе.
//
// Хранение: хост-линк (LinkKey) + доля длины его маршрута 0..1. Координаты не
// хранятся — T-соединение живёт при любом сдвиге блоков. Отдельный список, а не
// поле в Link: Link остаётся сравнимым значением, JSON v1 расширяется
// необязательным `taps`. Семантика §4.3. Разбор — docs/ALGORITHMS.md §3.2.

// Tap — якорь на линке-хозяине.
type Tap struct {
	// Host — ключ линка-хозяина в каноническом виде From → To (LinkKey).
	Host string `json:"host"`
	// T — доля длины маршрута хозяина (0..1). Держим долю, а не координату:
	// при перестройке маршрута точка остаётся на своей доле пути.
	T float32 `json:"t"`
}

// TapLink — провод от пина From до точки Tap на чужом линке.
type TapLink struct {
	From Endpoint `json:"from"`
	Tap  Tap      `json:"tap"`
}

// LinkKey — канонический ключ линка (From → To). Он же адресация Tap.Host.
func LinkKey(l Link) string { return l.From.String() + "->" + l.To.String() }

// TapFractionValid — доля лежит в 0..1 (с запасом на погрешность округления).
func (t Tap) FractionValid() bool { return t.T >= 0 && t.T <= 1 }
